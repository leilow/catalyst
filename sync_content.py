#!/usr/bin/env python3
"""Regenerate content/episodes.json from The Catalyst Schedule (Sheet) and Scripts (Doc).

A row becomes an episode when it has a Web Title, a Script link (to a tab in the
Scripts doc) and an Audio link. Titles, tags, links, audio and images always come
from the Sheet. The one-liner, script and sources come from the Doc, but only for
new episodes: the site text was lightly copy-edited, so for episodes already in
episodes.json the site text is kept and any later change in the Doc is reported
instead. Standard library only (plus the `openssl` command for Google sign-in).

    CATALYST_SHEET_ID=... python3 sync_content.py              # sync and report
    python3 sync_content.py --dry-run                          # report only
    python3 sync_content.py --from-doc 2026-10-16              # take the Doc's text for an episode
    python3 sync_content.py --keep-site 2026-10-16             # keep the site text, stop reporting it

--from-doc and --keep-site take comma-separated air dates, or "all".

Google access: set GOOGLE_SERVICE_ACCOUNT_JSON to the service account's JSON key
(or GOOGLE_APPLICATION_CREDENTIALS to its path, or save it as
.secrets/google-service-account.json). Without a key, the Sheet and Doc are read
as "anyone with the link" files.
"""
