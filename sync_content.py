ROOT = Path(__file__).resolve().parent
EPISODES = ROOT / "content" / "episodes.json"
IMAGES = ROOT / "content" / "images"
SNAPSHOT = ROOT / "content" / "doc-snapshot.json"
LOCAL_KEY = ROOT / ".secrets" / "google-service-account.json"

SHEET_TAB = "2026"
SCOPE = "https://www.googleapis.com/auth/drive.readonly"

NOTE = ("Generated by sync_content.py from The Catalyst Schedule (Sheet) and The Catalyst Scripts (Doc). "
        "Hand edits to oneLiner, script and source names are kept on the next sync.")
SNAPSHOT_NOTE = ("The Doc text sync_content.py last checked each episode against, so it can report "
                 "what changed in the Doc. Not used by the site.")

# Outlet names to use when a source isn't already named in episodes.json.
NAME_ALIASES = {
    "university of hawaiʻi news": "UH News",
    "university of hawai'i news": "UH News",
    "uh news": "UH News",
}


# ---------------------------------------------------------------- Google access

def b64url(b):
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def service_account():
    raw = os.environ.get("GOOGLE_SERVICE_ACCOUNT_JSON", "").strip()
    if not raw and os.environ.get("GOOGLE_APPLICATION_CREDENTIALS"):
        raw = Path(os.environ["GOOGLE_APPLICATION_CREDENTIALS"]).read_text()
    if not raw and LOCAL_KEY.exists():
        raw = LOCAL_KEY.read_text()
    return json.loads(raw) if raw else None


def access_token(sa):
    """Trade a service-account key for a short-lived read-only token (RS256 JWT, signed by openssl)."""
    now = int(time.time())
    token_uri = sa.get("token_uri", "https://oauth2.googleapis.com/token")
    header = b64url(json.dumps({"alg": "RS256", "typ": "JWT"}).encode())
    claims = b64url(json.dumps({
        "iss": sa["client_email"], "scope": SCOPE, "aud": token_uri, "iat": now, "exp": now + 3600,
    }).encode())
    signing_input = f"{header}.{claims}".encode()
    fd, key_path = tempfile.mkstemp(suffix=".pem")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(sa["private_key"])
        sig = subprocess.run(["openssl", "dgst", "-sha256", "-sign", key_path],
                             input=signing_input, capture_output=True, check=True).stdout
    finally:
        os.unlink(key_path)
    body = urllib.parse.urlencode({
        "grant_type": "urn:ietf:params:oauth:grant-type:jwt-bearer",
        "assertion": f"{signing_input.decode()}.{b64url(sig)}",
    }).encode()
    with urllib.request.urlopen(urllib.request.Request(token_uri, data=body)) as r:
        return json.load(r)["access_token"]


class Google:
    def __init__(self):
        sa = service_account()
        self.token = access_token(sa) if sa else None
        self.who = sa["client_email"] if sa else "no key (link-shared files only)"

    def get(self, url):
        headers = {"User-Agent": "the-catalyst-sync"}
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=headers)) as r:
                body = r.read().decode("utf-8")
                final = r.geturl()
        except urllib.error.HTTPError as err:
            raise SystemExit(f"Google returned {err.code} for {url.split('?')[0]}. "
                             "Is the file shared with the service account?") from None
        if "accounts.google.com" in final:
            raise SystemExit(f"Google asked to sign in for {url.split('?')[0]}. "
                             "Share the file with the service account and set its key.")
        return body

    def sheet_rows(self, sheet_id):
        if self.token:
            url = (f"https://sheets.googleapis.com/v4/spreadsheets/{sheet_id}/values/"
                   f"{urllib.parse.quote(SHEET_TAB)}")
            return json.loads(self.get(url)).get("values", [])
        url = (f"https://docs.google.com/spreadsheets/d/{sheet_id}/gviz/tq?tqx=out:csv&headers=1"
               f"&sheet={urllib.parse.quote(SHEET_TAB)}")
        return list(csv.reader(io.StringIO(self.get(url))))

    def doc_tab_html(self, doc_id, tab_id):
        return self.get(f"https://docs.google.com/document/d/{doc_id}/export?format=html&tab={tab_id}")


# ---------------------------------------------------------------- Sheet

def drive_file_id(url):
    m = re.search(r"/file/d/([\w-]{20,})", url or "") or re.search(r"[?&]id=([\w-]{20,})", url or "")
    return m.group(1) if m else None


def script_link(url):
    m = re.search(r"/document/d/([\w-]{20,})", url or "")
    t = re.search(r"[?&#]tab=(t\.[\w-]+)", url or "")
    return (m.group(1), t.group(1)) if m and t else None


def parse_date(s):
    m = re.fullmatch(r"\s*(\d{1,2})/(\d{1,2})/(\d{4})\s*", s or "")
    if m:
        return dt.date(int(m[3]), int(m[1]), int(m[2]))
    try:
        return dt.date.fromisoformat(s.strip())
    except (ValueError, AttributeError):
        return None


def sheet_episodes(rows, warn):
    if not rows:
        raise SystemExit(f"Sheet tab {SHEET_TAB!r} is empty.")
    header = [h.strip().lower() for h in rows[0]]
    need = ["date", "web title", "tags", "script", "audio files", "image", "bytemarks url", "hpr links"]
    missing = [n for n in need if n not in header]
    if missing:
        raise SystemExit(f"Sheet is missing column(s): {', '.join(missing)}")
    out = []
    for n, row in enumerate(rows[1:], start=2):
        cell = lambda name: (row[header.index(name)] if header.index(name) < len(row) else "").strip()
        title, script, audio = cell("web title"), cell("script"), cell("audio files")
        if not (title and script and audio):
            continue
        d, link, audio_id = parse_date(cell("date")), script_link(script), drive_file_id(audio)
        if not d or not link or not audio_id:
            warn(f"Row {n} ({title}): skipped, couldn't read the "
                 + ("date" if not d else "Script tab link" if not link else "Audio Drive link"))
            continue
        image_cell = cell("image")
        image_id = drive_file_id(image_cell)
        if image_cell and not image_id:
            warn(f"Row {n} ({title}): Image isn't a link to a single Drive file, so it was ignored")
        out.append({
            "date": d.isoformat(),
            "title": title,
            "tags": [t.strip() for t in cell("tags").split(",") if t.strip()],
            "doc": link,
            "audioDriveId": audio_id,
            "imageDriveId": image_id,
            "bytemarks": cell("bytemarks url"),
            "hpr": cell("hpr links"),
        })
    return out


# ---------------------------------------------------------------- Doc

class Blocks(html.parser.HTMLParser):
    """Paragraphs and list items of an exported Doc tab, in order, with their links.

    Comments and footnotes are left out, and so is anything inside a table."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.blocks, self.cur, self.table, self.skip_a, self.done = [], None, 0, False, False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "table":
            self.table += 1
        if self.done or self.table:
            return
        if tag in ("p", "li", "h1", "h2", "h3", "h4", "h5", "h6"):
            self.cur = {"tag": "li" if tag == "li" else "p", "text": "", "links": []}
        elif tag == "a" and self.cur is not None:
            href = a.get("href") or ""
            if re.match(r"#(cmnt|ftnt)_ref", href):
                self.done = True  # the comment/footnote bodies at the end of the export
                self.cur = None
            elif href.startswith("#"):
                self.skip_a = True  # the [a] / [1] marker in the text
            elif href:
                self.cur["links"].append(unwrap(href))
        elif tag == "br" and self.cur is not None:
            self.cur["text"] += " "

    def handle_endtag(self, tag):
        if tag == "table":
            self.table -= 1
        if tag == "a":
            self.skip_a = False
        if tag in ("p", "li", "h1", "h2", "h3", "h4", "h5", "h6") and self.cur is not None:
            self.cur["text"] = re.sub(r"\s+", " ", self.cur["text"].replace("\xa0", " ")).strip()
            if self.cur["text"]:
                self.blocks.append(self.cur)
            self.cur = None

    def handle_data(self, data):
        if self.cur is not None and not self.skip_a and not self.table:
            self.cur["text"] += data


def unwrap(href):
    """Docs exports wrap links as google.com/url?q=<real url>."""
    p = urllib.parse.urlparse(href)
    if p.netloc.endswith("google.com") and p.path == "/url":
        return urllib.parse.parse_qs(p.query).get("q", [href])[0]
    return href


def clean_url(url):
    url = url.rstrip(".,;)]")
    p = urllib.parse.urlparse(url)
    q = [(k, v) for k, v in urllib.parse.parse_qsl(p.query, keep_blank_values=True) if not k.lower().startswith("utm_")]
    return urllib.parse.urlunparse(p._replace(query=urllib.parse.urlencode(q)))


OPENER = re.compile(r"listening to the catalyst", re.I)
SOURCES = re.compile(r"(primary )?sources?\s*:?", re.I)
PRONUNCIATION = re.compile(r"^pronunciation\b", re.I)
PHONETIC_PAREN = re.compile(r"\s*\((?=[^)]*-[A-Z]{2,})[A-Za-zʻ'\- ]+\)")
PHONETIC_CAPS = re.compile(r"\b[A-Z]{2,}(?:-[A-Z]{1,}){2,}\b")
URL = re.compile(r"https?://[^\s<>\"]+")


def house_style(text):
    """Match the site's copy: straight quotes, spaced em dashes, ʻokina only where it belongs."""
    # Hawaiian syllables end in vowels, so an ʻokina before a consonant is a misplaced apostrophe (Youʻre, Letʻs).
    text = re.sub(r"(?<=[A-Za-z])ʻ(?=[b-df-hj-np-tv-zB-DF-HJ-NP-TV-Z])", "'", text)
    text = text.replace("’", "'").replace("“", '"').replace("”", '"')
    return re.sub(r"\s*—\s*", " — ", text)


def parse_tab(page):
    """-> (oneLiner, [script paragraphs], [(label, url)], [warnings])"""
    p = Blocks()
    p.feed(page)
    blocks = p.blocks
    warnings = []

    one_liner, start, after_one = None, None, None
    for i, b in enumerate(blocks):
        t = b["text"]
        if OPENER.search(t):
            start = i + 1
            break
        if re.fullmatch(r"script\s*:?", t, re.I):
            start = i + 1
            break
        m = re.search(r"one-?liner\s*:?\s*(.*)", t, re.I)
        if m and one_liner is None:
            rest = re.split(r"\s*read time\s*:", m.group(1), flags=re.I)[0].strip()
            if rest:
                one_liner, after_one = rest, i + 1
            elif i + 1 < len(blocks):
                one_liner, after_one = blocks[i + 1]["text"], i + 2
    if start is None:
        start = after_one or 0
        warnings.append("couldn't find where the script starts; started after the one-liner")
    if not one_liner:
        warnings.append("no one-liner found")

    script, end = [], len(blocks)
    for i in range(start, len(blocks)):
        b, t = blocks[i], blocks[i]["text"]
        if b["tag"] == "li" or SOURCES.fullmatch(t):
            end = i + 1 if SOURCES.fullmatch(t) else i
            break
        if PRONUNCIATION.match(t) or re.match(r"read time\s*:", t, re.I) or OPENER.search(t):
            continue
        script.append(house_style(PHONETIC_PAREN.sub("", t)))
    # a short heading just above the source list ("Coworking origins / Brad Neuberg") isn't script
    while script and not re.search(r"[.?!\"”'’)]$", script[-1]):
        script.pop()
    for s in script:
        for m in PHONETIC_CAPS.findall(s):
            warnings.append(f"script has what looks like a pronunciation guide: {m}")

    sources, seen = [], set()
    for b in blocks[end:]:
        if PRONUNCIATION.match(b["text"]):
            continue
        urls = URL.findall(b["text"]) or [u for u in b["links"] if u.startswith("http")]
        label = URL.sub("", b["text"]).strip(" —–-:|")
        for u in urls:
            u = clean_url(unwrap(u))
            key = u.rstrip("/").lower()
            if key not in seen:
                seen.add(key)
                sources.append((label, u))
    return house_style(one_liner or ""), script, sources, warnings


# ---------------------------------------------------------------- naming and merging

def slugify(date, title):
    s = unicodedata.normalize("NFKD", title.replace("ʻ", "").replace("’", "").replace("'", ""))
    s = re.sub(r"[^a-z0-9]+", "-", s.encode("ascii", "ignore").decode().lower()).strip("-")
    return f"{date}-{s}"


def url_keys(url):
    p = urllib.parse.urlparse(url)
    host = p.netloc.lower().removeprefix("www.")
    seg = p.path.strip("/").split("/")[0]
    return url.rstrip("/").lower(), f"{host}/{seg}", host


class Namer:
    """Name sources the way earlier episodes did, else from the Doc's label, else the hostname."""

    def __init__(self, episodes):
        found = {}
        for ep in episodes:
            for s in ep.get("sources", []):
                for k in url_keys(clean_url(s["url"])):
                    found.setdefault(k, set()).add(s["name"])
        self.known = {k: v.pop() for k, v in found.items() if len(v) == 1}

    def __call__(self, label, url):
        for k in url_keys(url):
            if k in self.known:
                return self.known[k], False
        paren = re.search(r"\(([^()\d]{2,40})\)\s*$", label)  # "(Kauai Now)", not "(July 9, 2026)"
        first = re.split(r"\s+[—–-]\s+|:\s", label)[0].strip(" \"“”")
        for cand in (first, paren.group(1) if paren else None):
            if cand and len(cand.split()) <= 4:
                return NAME_ALIASES.get(cand.lower(), cand), True
        return url_keys(url)[2], True


def local_image(date):
    for ext in ("webp", "jpg", "jpeg", "png"):
        if (IMAGES / f"{date}.{ext}").exists():
            return f"images/{date}.{ext}"
    return None


def text_diff(a, b):
    """Line diff of two {oneLiner, script, sources} versions."""
    lines = []
    if a["oneLiner"] != b["oneLiner"]:
        lines += [f"- {a['oneLiner']}", f"+ {b['oneLiner']}"]
    lines += [l for l in difflib.unified_diff(a["script"], b["script"], lineterm="", n=0)
              if not l.startswith(("---", "+++", "@@"))]
    lines += [f"- source {u}" for u in a["sources"] if u not in b["sources"]]
    lines += [f"+ source {u}" for u in b["sources"] if u not in a["sources"]]
    return lines


def pick(arg):
    return {"all"} if arg == "all" else {d.strip() for d in (arg or "").split(",") if d.strip()}


def sync(rows, fetch_tab, current, snapshot, from_doc, keep_site):
    """-> (episodes, new snapshot, report). snapshot maps air date -> the Doc text last checked."""
    report = {"new": [], "removed": [], "changes": [], "review": [], "baseline": [], "warnings": []}
    warn = report["warnings"].append
    by_date = {ep["date"]: ep for ep in current}
    namer = Namer(current)
    out, snap = [], {}

    for row in sheet_episodes(rows, warn):
        d = row["date"]
        old = by_date.pop(d, None)
        one, script, srcs, tab_warnings = parse_tab(fetch_tab(*row["doc"]))
        for w in tab_warnings:
            warn(f"{d} {row['title']}: {w}")
        doc = {"oneLiner": one, "script": script, "sources": [u for _, u in srcs]}

        def named():
            res = []
            for label, url in srcs:
                name, guessed = namer(label, url)
                if guessed:
                    warn(f"{d} {row['title']}: guessed source name {name!r} for {url}")
                res.append({"name": name, "url": url})
            return res

        ep = {
            "date": d,
            "slug": old["slug"] if old else slugify(d, row["title"]),
            "title": row["title"],
            "oneLiner": one,
            "audioDriveId": row["audioDriveId"],
            "image": local_image(d),
            "bytemarks": row["bytemarks"],
            "hpr": row["hpr"],
            "tags": row["tags"],
            "script": script,
            "sources": None,
        }
        if row["imageDriveId"]:
            ep["imageDriveId"] = row["imageDriveId"]
        out.append(ep)
        snap[d] = doc

        if not old:
            ep["sources"] = named()
            report["new"].append(f"{d} {row['title']} → episodes/{ep['slug']}/")
            continue

        for key in ("title", "tags", "bytemarks", "hpr", "audioDriveId", "image", "imageDriveId"):
            if old.get(key) != ep.get(key):
                report["changes"].append(f"{d} {key}: {old.get(key)!r} → {ep.get(key)!r}")
        if old["title"] != ep["title"]:
            report["changes"].append(f"{d} kept the old web address episodes/{old['slug']}/ so links don't break")

        if d in from_doc or "all" in from_doc:
            ep["sources"] = named()
            report["changes"].append(f"{d} took the one-liner, script and sources from the Doc")
            continue
        # keep the copy-edited site text
        ep["oneLiner"], ep["script"], ep["sources"] = old["oneLiner"], old["script"], old["sources"]
        seen = snapshot.get(d)
        if seen is None:
            site = {"oneLiner": old["oneLiner"], "script": old["script"], "sources": [s["url"] for s in old["sources"]]}
            if site != doc:
                report["baseline"].append((f"{d} {row['title']}", text_diff(site, doc)))
        elif seen != doc and not (d in keep_site or "all" in keep_site):
            snap[d] = seen  # keep reporting until it's resolved
            report["review"].append((f"{d} {row['title']}", text_diff(seen, doc)))

    report["removed"] = [f"{d} {ep['title']}" for d, ep in by_date.items()]
    out.sort(key=lambda ep: ep["date"], reverse=True)
    return out, dict(sorted(snap.items(), reverse=True)), report


def format_report(report, status):
    lines = []
    def section(title, items):
        if items:
            lines.append(f"\n## {title}\n")
            for it in items:
                if isinstance(it, tuple):
                    lines.append(f"### {it[0]}\n")
                    lines.append("```diff")
                    lines.extend(it[1])
                    lines.append("```")
                else:
                    lines.append(f"- {it}")
    section("New episodes", report["new"])
    section("Removed (no longer a complete row in the Sheet)", report["removed"])
    section("Changes", report["changes"])
    section("The Doc changed (the site text was kept)", report["review"])
    if report["review"]:
        lines.append("\nTo use the Doc's version run `python3 sync_content.py --from-doc DATE`; to keep the "
                     "site text and stop this note run `--keep-site DATE`. Both are also inputs on the "
                     "workflow's \"Run workflow\" button.")
    section("Doc and site text differ (shown once; the site text was kept)", report["baseline"])
    section("Warnings", report["warnings"])
    lines.insert(0, f"# Content sync: {status}")
    return "\n".join(lines) + "\n"


def write_json(path, data, dry_run):
    """Write data if it changed (unless dry_run); return whether it changed."""
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    if not dry_run:
        path.write_text(text, encoding="utf-8")
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--sheet", default=os.environ.get("CATALYST_SHEET_ID"), help="Sheet id (or CATALYST_SHEET_ID)")
    ap.add_argument("--dry-run", action="store_true", help="report only; don't write any files")
    ap.add_argument("--from-doc", default="", help="air dates (or 'all') to take the Doc's text for")
    ap.add_argument("--keep-site", default="", help="air dates (or 'all') to keep the site text for")
    args = ap.parse_args()
    if not args.sheet:
        print("No Sheet id (set CATALYST_SHEET_ID). Skipping the sync; the build uses episodes.json as it is.")
        return

    g = Google()
    print(f"Reading the Sheet and Doc as {g.who}", file=sys.stderr)
    current = json.loads(EPISODES.read_text(encoding="utf-8"))["episodes"]
    snapshot = json.loads(SNAPSHOT.read_text(encoding="utf-8")) if SNAPSHOT.exists() else {}
    snapshot.pop("_note", None)
    episodes, snap, report = sync(g.sheet_rows(args.sheet), g.doc_tab_html, current, snapshot,
                                  pick(args.from_doc), pick(args.keep_site))
    changed = write_json(EPISODES, {"_note": NOTE, "episodes": episodes}, args.dry_run)
    changed |= write_json(SNAPSHOT, {"_note": SNAPSHOT_NOTE, **snap}, args.dry_run)

    out = format_report(report, "no changes" if not changed else "would update content (dry run)"
                        if args.dry_run else "content updated")
    print(out)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a", encoding="utf-8") as f:
            f.write(out)
    if os.environ.get("GITHUB_ACTIONS"):
        for title, _ in report["review"]:
            print(f"::warning title=Doc changed::{title}: the Doc's text changed; see the run summary")


if __name__ == "__main__":
    main()
